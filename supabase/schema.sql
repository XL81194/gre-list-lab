-- GRE List Lab cloud progress and feedback schema
-- Run this entire file once in Supabase Dashboard -> SQL Editor.

create table if not exists public.user_progress (
    user_id uuid primary key references auth.users(id) on delete cascade,
    state jsonb not null default '{}'::jsonb,
    client_updated_at timestamptz,
    updated_at timestamptz not null default now()
);

alter table public.user_progress enable row level security;

revoke all on table public.user_progress from anon;
revoke all on table public.user_progress from authenticated;
grant select, insert, update, delete on table public.user_progress to authenticated;

drop policy if exists "progress_select_own" on public.user_progress;
create policy "progress_select_own"
on public.user_progress for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "progress_insert_own" on public.user_progress;
create policy "progress_insert_own"
on public.user_progress for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "progress_update_own" on public.user_progress;
create policy "progress_update_own"
on public.user_progress for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists "progress_delete_own" on public.user_progress;
create policy "progress_delete_own"
on public.user_progress for delete
to authenticated
using ((select auth.uid()) = user_id);

create table if not exists public.feedback (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete set null,
    client_id text not null,
    category text not null,
    impact text not null,
    message text not null,
    contact text,
    context jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    constraint feedback_category_length check (char_length(category) between 2 and 40),
    constraint feedback_impact_length check (char_length(impact) between 2 and 40),
    constraint feedback_message_length check (char_length(message) between 4 and 2000),
    constraint feedback_contact_length check (contact is null or char_length(contact) <= 160),
    constraint feedback_client_id_length check (char_length(client_id) between 8 and 100)
);

create index if not exists feedback_created_at_idx on public.feedback (created_at desc);
create index if not exists feedback_category_idx on public.feedback (category);

alter table public.feedback enable row level security;

revoke all on table public.feedback from anon;
revoke all on table public.feedback from authenticated;
grant insert on table public.feedback to anon, authenticated;
grant usage, select on sequence public.feedback_id_seq to anon, authenticated;

drop policy if exists "feedback_insert_public" on public.feedback;
create policy "feedback_insert_public"
on public.feedback for insert
to anon, authenticated
with check (
    (user_id is null or user_id = (select auth.uid()))
    and char_length(message) between 4 and 2000
    and char_length(client_id) between 8 and 100
);

-- No SELECT policy is intentionally created for feedback.
-- Visitors can submit feedback but cannot read anyone's submissions.
